/// rakuos-flatpak-wrapper-gen — generate CLI wrapper scripts for exported Flatpak
/// apps in /usr/local/bin/flatpak, so `some-app` on the CLI runs `flatpak run some.app.Id`.
use anyhow::Result;
use std::collections::HashMap;
use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::Path;

const SRC: &str = "/var/lib/flatpak/exports/bin";
const DEST: &str = "/usr/local/bin/flatpak";
const OVERRIDE_FILE: &str = "/usr/share/rakuos/flatpak-command-overrides.conf";
const TAG: &str = "# Generated by RakuOS Flatpak Wrapper";

fn main() -> Result<()> {
    fs::create_dir_all(DEST)?;

    let overrides = load_overrides(OVERRIDE_FILE);

    wipe_dir(DEST);

    if !Path::new(SRC).is_dir() {
        return Ok(());
    }

    generate_wrappers(SRC, DEST, &overrides);

    Ok(())
}

fn load_overrides(path: &str) -> HashMap<String, String> {
    let mut overrides = HashMap::new();
    let Ok(content) = fs::read_to_string(path) else {
        return overrides;
    };

    for line in content.lines() {
        let key_part = line.split('=').next().unwrap_or("").trim();
        if key_part.is_empty() || key_part.starts_with('#') {
            continue;
        }
        let Some((key, value)) = line.split_once('=') else { continue };
        overrides.insert(key.trim().to_string(), value.trim().to_string());
    }

    overrides
}

// Mirrors the original `rm -rf $DEST/*` — wipes everything in DEST, not just
// tagged wrappers, so any manual additions there don't survive a regen.
fn wipe_dir(dest: &str) {
    let Ok(entries) = fs::read_dir(dest) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            let _ = fs::remove_dir_all(&path);
        } else {
            let _ = fs::remove_file(&path);
        }
    }
}

fn generate_wrappers(src: &str, dest: &str, overrides: &HashMap<String, String>) {
    let Ok(entries) = fs::read_dir(src) else { return };

    for entry in entries.flatten() {
        let export = entry.path();
        if !export.is_file() {
            continue;
        }

        let app_id = match export.file_name() {
            Some(n) => n.to_string_lossy().to_string(),
            None => continue,
        };

        let cmd_name = overrides
            .get(&app_id)
            .cloned()
            .unwrap_or_else(|| default_cmd_name(&app_id));

        let wrapper = Path::new(dest).join(&cmd_name);

        // Do not override real system binaries
        if let Some(real_path) = which(&cmd_name) {
            if real_path != wrapper {
                continue;
            }
        }

        let script = format!("#!/usr/bin/env bash\n{TAG}\nexec flatpak run {app_id} \"$@\"\n");
        if fs::write(&wrapper, script).is_ok() {
            if let Ok(meta) = fs::metadata(&wrapper) {
                let mut perms = meta.permissions();
                perms.set_mode(perms.mode() | 0o111);
                let _ = fs::set_permissions(&wrapper, perms);
            }
        }
    }
}

fn default_cmd_name(app_id: &str) -> String {
    app_id
        .rsplit('.')
        .next()
        .unwrap_or(app_id)
        .to_lowercase()
}

fn which(bin: &str) -> Option<std::path::PathBuf> {
    let path = std::env::var_os("PATH")?;
    std::env::split_paths(&path)
        .map(|p| p.join(bin))
        .find(|p| p.is_file())
}
